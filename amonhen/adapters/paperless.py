"""Paperless-ngx as the documents' source: its REST API, read by type, written back by tag.

Pulled, not pushed: the documents of a type modified after the last stamp, each downloaded
as the **original** (`?original=true`), because the archived copy is a PDF/A regenerated by
OCR and can move the text the parser reads by coordinates. The outcome goes back as a tag
(`amonhen:importato` or `amonhen:errore`) and the key figures as custom fields, created on
first use. Every failure of the API is a `SourceUnavailable`, with Paperless's own words.
"""
from __future__ import annotations

import requests

from amonhen.adapters.payslips import Parse, read_document
from amonhen.ports.portfolio import FAILED, IMPORTED, FetchedDocument, SourceUnavailable

TAGS = {IMPORTED: "amonhen:importato", FAILED: "amonhen:errore"}


class PaperlessDocuments:
    """The `DocumentSource` port over Paperless's REST API."""

    def __init__(self, base_url: str, token: str, types: dict[str, str], *, parse: Parse | None = None,
                 session: requests.Session | None = None, timeout: float = 30) -> None:
        self.base = base_url.rstrip("/")
        self.types = types  # kind -> the Paperless document type's name
        self.parse = parse
        self.timeout = timeout
        self.http = session or requests.Session()
        self.http.headers.update({"Authorization": f"Token {token}", "Accept": "application/json"})

    # -- the port ----------------------------------------------------------

    def list_new(self, kind: str, modified_after: str | None) -> list[tuple[int, str]]:
        params = {"document_type__id": self._id("document_types", self.types[kind]),
                  "ordering": "modified", "page_size": 100, "fields": "id,modified"}
        if modified_after:
            params["modified__gt"] = modified_after
        found, url = [], f"{self.base}/api/documents/"
        while url:
            page = self._get(url, params)
            found += [(row["id"], row["modified"]) for row in page["results"]]
            url, params = page.get("next"), None
        return found

    def read(self, kind: str, source_id: int) -> FetchedDocument:
        response = self._call("GET", f"{self.base}/api/documents/{source_id}/download/", params={"original": "true"})
        if self.parse is None:
            return read_document(source_id, kind, response.content)
        return read_document(source_id, kind, response.content, self.parse)

    def report(self, source_id: int, outcome: str, figures: dict[str, str]) -> None:
        document = self._get(f"{self.base}/api/documents/{source_id}/")
        other = {self._id("tags", name, create=False) for key, name in TAGS.items() if key != outcome}
        tags = [tag for tag in document.get("tags", []) if tag not in other]
        tag = self._id("tags", TAGS[outcome], create=True)
        if tag not in tags:
            tags.append(tag)
        fields = {item["field"]: item["value"] for item in document.get("custom_fields", [])}
        for name, value in figures.items():
            fields[self._id("custom_fields", name, create=True)] = value
        self._call("PATCH", f"{self.base}/api/documents/{source_id}/", json={
            "tags": tags, "custom_fields": [{"field": key, "value": value} for key, value in fields.items()]})

    # -- the API -----------------------------------------------------------

    def _id(self, collection: str, name: str, *, create: bool = False) -> int | None:
        """The id of a document type, tag or custom field by its exact name; created on request."""
        page = self._get(f"{self.base}/api/{collection}/", {"name__iexact": name})
        if page["results"]:
            return page["results"][0]["id"]
        if collection == "document_types":
            raise SourceUnavailable(f"Paperless non ha un tipo di documento chiamato {name!r}")
        if not create:
            return None
        body = {"name": name} if collection == "tags" else {"name": name, "data_type": "string"}
        return self._call("POST", f"{self.base}/api/{collection}/", json=body).json()["id"]

    def _get(self, url: str, params: dict | None = None) -> dict:
        return self._call("GET", url, params=params).json()

    def _call(self, method: str, url: str, **kwargs) -> requests.Response:
        try:
            response = self.http.request(method, url, timeout=self.timeout, **kwargs)
        except requests.RequestException as exc:
            raise SourceUnavailable(f"Paperless non risponde: {exc}") from exc
        if response.status_code >= 400:
            raise SourceUnavailable(f"Paperless ha risposto {response.status_code}: {response.text[:300]}")
        return response
